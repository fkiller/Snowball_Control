"""Generate the embedded 16px Hangul atlas (Pillow needed only to regenerate).

Input: https://github.com/neodgm/neodgm/releases/download/v1.601/neodgm.ttf
The generated subset is named Snowball Hangul Pixels, under SIL OFL 1.1.
Builds use the checked-in atlas and require no font download or Python package.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('font', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
font = ImageFont.truetype(str(args.font), 16)
missing = bytes(font.getmask(chr(0xFFFF)))
ranges = [(0x1100, 0x1112), (0x1161, 0x1175), (0x11A8, 0x11C2), (0x3131, 0x3163), (0xAC00, 0xD7A3)]
digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
out = ['/* Snowball Hangul Pixels: 16x16 monochrome subset of NeoDunggeunmo v1.601.',
       ' * Copyright (c) 2017-2021 Eunbin Jeong. SIL OFL 1.1; see fonts/OFL.txt.',
       f' * Source TTF SHA-256: {digest}',
       ' * Generated by dev-tools/generate-hangul-font.py; do not edit. */',
       '#ifndef SNOWBALL_HANGUL_PIXELS_H', '#define SNOWBALL_HANGUL_PIXELS_H', '#include <stdint.h>',
       'static const uint16_t snowball_hangul_pixels[][16] = {']
for start, end in ranges:
    for cp in range(start, end + 1):
        if bytes(font.getmask(chr(cp))) == missing:
            raise ValueError(f'Source font is missing U+{cp:04X}')
        image = Image.new('1', (16, 16))
        ImageDraw.Draw(image).text((0, 12), chr(cp), font=font, fill=1, anchor='ls', stroke_width=0)
        rows = [sum((1 << (15 - x)) for x in range(16) if image.getpixel((x, y))) for y in range(16)]
        out.append('{' + ','.join(f'0x{row:04x}' for row in rows) + '},')
out += ['};', 'static const uint16_t *hangul_pixels(unsigned cp) {']
offset = 0
for start, end in ranges:
    out.append(f'    if (cp >= 0x{start:x} && cp <= 0x{end:x}) return snowball_hangul_pixels[cp - 0x{start:x} + {offset}];')
    offset += end - start + 1
out += ['    return 0;', '}', '#endif', '']
args.output.write_text('\n'.join(out), encoding='utf-8')
print(f'{offset} glyphs / {offset * 32} bitmap bytes; source SHA-256 {digest}')
